export type UIKey = keyof (typeof UI)["es"];

export const t = (lang: Lang, key: UIKey): string => UI[lang][key];

export const isLang = (x: unknown): x is Lang => x === "es" || x === "en";

export const localePath = (lang: Lang, path = "") => `/${lang}/${path.replace(/^\//, "")}`;

export const fmtPeriod = (lang: Lang, start: string, end?: string) => {
  const f = (ym: string) => {
    const [y, m] = ym.split("-").map(Number);
    return new Date(Date.UTC(y ?? 2000, (m ?? 1) - 1, 1)).toLocaleDateString(lang === "es" ? "es-PE" : "en-US", {
      month: "short",
      year: "numeric",
      timeZone: "UTC",
    });
  };
  return `${f(start)} – ${end ? f(end) : UI[lang]["chapters.present"]}`;
};
